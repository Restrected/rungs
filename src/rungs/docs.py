def render_agents_md(roster: Roster, ctx) -> str:
    project = one_line(str(roster.project), PROJECT_MAX) if roster.project else ""
    project = project or "this project"
    lines: List[str] = []
    lines.append("# rungs — how work is run in {0}".format(project))
    lines.append("")
    lines.append(GENERATED_NOTE + " Run `rungs docs` after changing `rungs.yaml`.")
    lines.append("")

    lines.append("## What this is")
    lines.append("")
    lines += [
        "`rungs` is a file-based ticket system. Every ticket is one markdown file under `.rungs/`,",
        "and **the folder a ticket sits in is its status**: `triage/`, `open/`, `in_progress/`,",
        "`review/`, `blocked/`, `shelved/`, `closed/YYYY-MM/`. There is no database and no server,",
        "so the tickets travel with the repository and you can read one with `cat`. Tickets are",
        "rungs on a ladder: each ticket names the lowest skill level that can work it, each agent",
        "is registered in `rungs.yaml` with a level, and the tool only offers you the rungs you can",
        "reach. Work arrives either from the director (who designs a batch in a plan and cuts it",
        "into tickets) or from outside the project through `inbox/`. Every state change is appended",
        "to `.rungs/events.jsonl`, so what happened stays recoverable.",
    ]
    lines.append("")

    lines.append("## Quick start for an agent")
    lines.append("")
    lines += _quick_start(roster)
    lines.append("")

    lines.append("## Roster")
    lines.append("")
    lines += _roster_table(roster)
    lines.append("")
    lines.append("The ladder, lowest rung first:")
    lines.append("")
    lines += _ladder_table()
    lines.append("")
    lines += [
        "\"At or below\" means by rung number: an agent at rung 4 may claim tickets at rungs 1-4 and",
        "is refused at rung 5. A **floor** is a preference, not a rule: `rungs next` leaves out",
        "tickets below your floor and says on stderr how many it left out, `--ignore-floor` shows",
        "them, and a direct `rungs claim` never looks at the floor.",
    ]
    lines.append("")

    lines.append("## Rules")
    lines.append("")
    lines += _rules(roster)
    lines.append("")

    lines.append("## Ticket fields")
    lines.append("")
    lines += _TICKET_FIELDS
    lines.append("")
    lines += [
        "Aliases accepted for `skill` on input: `vlow`, `xlow`, `1`-`5`, `very-high`. The file",
        "always stores the canonical name.",
    ]
    lines.append("")

    lines.append("## Lifecycle")
    lines.append("")
    lines += _LIFECYCLE
    lines.append("")

    lines.append("## Intake")
    lines.append("")
    lines += [
        "Outside systems (an application's \"request a change\" button, a support queue, a script)",
        "never write ticket files. They drop one small JSON file per request into `.rungs/inbox/`.",
        "`rungs intake` validates and sanitises each one, refuses a source that is not listed under",
        "`intake.sources` in `rungs.yaml`, deduplicates on `origin` (`source:key`), creates the",
        "ticket in `triage/` (or in `open/` when the source is marked `ready: true` and the request",
        "carries acceptance criteria), moves the file to `inbox/done/` and writes",
        "`inbox/done/<name>.result.json` so the producer can read what happened. Arbite-format",
        "`.md` files dropped in the inbox are accepted too. Anyone who would rather not write",
        "JSON can file one request with `rungs request --source S --key K --title T --goal G`,",
        "which goes through the same validation and the same creation path. `rungs triage` lists",
        "what is waiting for a triager. The producer contract is in `docs/INTAKE.md`.",
        "Scheduler line:",
        "",
        "```",
        "*/5 * * * * cd /path/to/project && rungs intake --quiet",
        "```",
    ]
    lines.append("")

    lines.append("## Plans")
    lines.append("")
    lines += [
        "A director designs a batch once in `.rungs/plans/<slug>.md`: a front matter, the design,",
        "then a `## Tickets` section where each `### <key> — <title>` block carries a bullet list",
        "of fields (`kind`, `skill`, `domain`, `priority`, `tags`, `scope`, `depends_on`, `epic`)",
        "and the `#### Goal`, `#### Decisions already made`, `#### Constraints`,",
        "`#### Acceptance criteria` and `#### Evidence required` sections. `rungs cut <slug>`",
        "validates the whole file first and then creates every ticket with its dependencies",
        "resolved, writing the key-to-id table back into the plan, so cutting a plan twice is safe.",
        "The grammar is in `docs/PLANS.md`.",
    ]
    lines.append("")

    lines.append("## Exit codes")
    lines.append("")
    lines += _EXIT_CODES
    lines.append("")

    lines.append("## Command reference")
    lines.append("")
    if ctx is not None and getattr(ctx, "subparsers", None):
        lines += [
            "Run `rungs <command> --help` for the flags and details before first using a command;",
            "the table below is only for finding the right one. Most commands take `--json` for",
            "machine-readable output and `--agent <you>` to say who is acting.",
            "",
        ]
        lines += _command_table(ctx)
        lines.append("")
    else:  # pragma: no cover - only when rendered outside the CLI
        lines.append("(no command parser available)")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def write_docs(store: Store, roster: Roster, ctx, force_agent_files: bool = False) -> List[Path]:
    """Write `.rungs/AGENTS.md` and every roster agent's file. Returns the paths."""
    from .ticket import write_atomic

    store.root.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    guide = store.root / "AGENTS.md"
    write_atomic(render_agents_md(roster, ctx), guide)
    written.append(guide)
    for agent in roster.by_skill():
        written.append(write_agent_file(store, agent.id, agent, roster, force=force_agent_files))
    return written


# --------------------------------------------------------------------------
# Command
# --------------------------------------------------------------------------


def _docs(args, ctx) -> Optional[int]:
    store = ctx.store
    roster = ctx.roster
    written = write_docs(store, roster, ctx, force_agent_files=bool(getattr(args, "force", False)))
    if ctx.json_output:
        ctx.emit_json({"written": [str(p) for p in written]})
    else:
        for path in written:
            try:
                shown = path.relative_to(ctx.cwd)
            except ValueError:
                shown = path
            ctx.out("wrote {0}".format(shown))
    if not roster.agents:
        ctx.warn("no agents in rungs.yaml: add them before any work can be claimed")
    return 0


def register(subparsers, ctx) -> None:
    parser = ctx.command(
        subparsers, "docs", _docs,
        help="regenerate .rungs/AGENTS.md and the agent file headers",
        description=(
            "Regenerate .rungs/AGENTS.md and the generated header of every roster agent's file\n"
            "under .rungs/agents/. Everything below the line\n"
            "    " + MARKER + "\n"
            "in an agent file is left alone, so the 'Current work' section the lifecycle commands\n"
            "maintain survives. Run this after editing rungs.yaml."
        ),
    )
    parser.add_argument(
        "--force", action="store_true",
        help="rewrite agent files completely, discarding the part below the generated header",
    )
    ctx.add_json_option(parser)
