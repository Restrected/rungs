def _ladder_table() -> List[str]:
    return [
        "| Rung | Level | Typical work |",
        "|---|---|---|",
        "| 1 | very-low | mechanical edits, sweeps, digests, running a check |",
        "| 2 | low | routine multi-file work with a clear recipe |",
        "| 3 | medium | ordinary implementation inside a known design |",
        "| 4 | high | harder implementation, security-sensitive code, review |",
        "| 5 | xhigh | architecture, plans, the decisions nobody else may take |",
    ]


def _roster_table(roster: Roster) -> List[str]:
    if not roster.agents:
        return [
            "No agents are registered yet. Add them to `rungs.yaml` before any work can be",
            "claimed; `rungs deploy --agent id:skill[:role[:floor]]` adds them for you.",
        ]
    lines = ["| Agent id | Skill | Rung | Role | Floor |", "|---|---|---|---|---|"]
    for agent in roster.by_skill():
        lines.append(
            "| `{0}` | {1} | {2} | {3} | {4} |".format(
                agent.id, agent.skill, agent.rank, agent.role, agent.floor or "—"
            )
        )
    return lines


