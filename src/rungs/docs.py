from typing import List, Optional, Tuple

from .roster import Agent, Roster
from .store import Store
from .ticket import SKILLS, one_line

__all__ = [
    "MARKER", "GENERATED_NOTE", "register", "agent_header", "agent_file_text",
    "write_agent_file", "render_agents_md", "write_docs",
]


MARKER = "<!-- end of generated header -->"
# The project name is rendered into a heading and a bullet; it comes from
# rungs.yaml, so it is flattened to one line first.
PROJECT_MAX = 80
GENERATED_NOTE = "Generated by `rungs docs`. Hand edits above the marker are overwritten."

_ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")

_ROLE_NOTE = {
    "director": "designs the work, cuts tickets, may review, may close without a review",
    "executor": "claims tickets, works them, submits evidence",
    "reviewer": "reviews submitted tickets and accepts or returns them",
    "critic": "critiques plans and direction; does not close work",
}


