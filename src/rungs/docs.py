        "   set `RUNGS_AGENT` once in your environment.",
        "2. **Resume before you start.** Read your own file, `.rungs/agents/<you>.md`, under",
        "   *Current work*, then confirm it against the store with `rungs list --assignee <you>`.",
        "   If a ticket is already yours, finish that one before taking another.",
        "3. **Pick work.** `rungs next --agent <you> --claim` claims the best ticket you can reach.",
        "   Without `--claim` it only shows what is available; `--count 3` shows more. A ticket",
        "   above your level is refused: that is the point of the ladder.",
        "4. **Read the whole ticket.** `rungs show <id>`. Goal, Decisions already made, Constraints,",
        "   Acceptance criteria and Evidence required are your brief. Do not reopen a decision that",
        "   is already written down; if one is wrong, say so in a note and hand the ticket back.",
        "5. **Work inside the scope only.** The ticket's `scope` lists the paths you may change, and",
        "   nothing else. If the work needs a file outside it, do not edit it: note it and stop.",
        "   `rungs verify <id> --tree` compares what you touched against the scope.",
        "6. **Note progress as you go.** `rungs note <id> --agent <you> \"what changed and why\"`.",
        "   Notes are how the director follows the work without reading your diff.",
        "7. **Submit with evidence.**",
        "   `rungs submit <id> --agent <you> --summary \"...\" --files src/a.py,tests/test_a.py`",
