"""Generated documentation: `.rungs/AGENTS.md` and the agent file headers.

Everything here is rendered from the tool itself and from `rungs.yaml`, so the
guide an agent reads cold can never drift from the commands that exist. The
agent files keep a hand/lifecycle-maintained part below a marker line; only
the part above it is regenerated.
"""

from __future__ import annotations

import re
