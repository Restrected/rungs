def agent_header(agent_id: str, agent: Optional[Agent], roster: Optional[Roster] = None) -> str:
    """The generated part of `.rungs/agents/<id>.md`, ending with the marker."""
    lines = ["# " + agent_id, "", GENERATED_NOTE, ""]
    if agent is None:
        lines += [
            "This agent is **not in `rungs.yaml`**, so it has no skill level and cannot claim",
            "work until someone adds it to the roster.",
            "",
        ]
    else:
        lines += [
            "- Skill level: **{0}** (rung {1} of {2}). You may claim a ticket whose `skill` is "
            "{0} or below.".format(agent.skill, agent.rank, len(SKILLS)),
            "- Role: **{0}** — {1}.".format(agent.role, _ROLE_NOTE.get(agent.role, "see .rungs/AGENTS.md")),
            "- Floor: "
            + (
                "**{0}** — `rungs next` leaves out tickets below it by default "
                "(`--ignore-floor` shows them).".format(agent.floor)
                if agent.floor
                else "none — `rungs next` offers every rung you can reach."
            ),
        ]
        if roster is not None and roster.project:
            # The project name reaches here from rungs.yaml; it is data, and it
            # must not be able to add a line of its own to a generated file.
            lines.append("- Project: " + one_line(str(roster.project), PROJECT_MAX))
        lines += [
            "",
            "Find work with `rungs next --agent {0} --claim`, then read the ticket in full.".format(agent_id),
            "Read `.rungs/AGENTS.md` before your first ticket: it holds the workflow, the rules",
            "and the command reference.",
            "",
        ]
    lines.append(MARKER)
    return "\n".join(lines) + "\n"


def agent_file_text(
    agent_id: str, agent: Optional[Agent], roster: Optional[Roster], existing: Optional[str]
) -> str:
    """The whole agent file: the generated header plus whatever sat below the
    marker before (a fresh file gets an empty 'Current work' section)."""
    header = agent_header(agent_id, agent, roster)
    tail = "## Current work\n- none\n"
    if existing and MARKER in existing:
        after = existing.split(MARKER, 1)[1].lstrip("\n")
        if after.strip():
            tail = after
    return header + "\n" + tail


def write_agent_file(
    store: Store, agent_id: str, agent: Optional[Agent], roster: Optional[Roster], force: bool = False
) -> Path:
    """Rewrite the header of an agent file, preserving the part below the
    marker. `force` throws that part away and starts the file again."""
    from .ticket import write_atomic

    path = store.agent_file(agent_id)
    existing = None
    if not force and path.is_file():
        try:
            existing = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            existing = None
    text = agent_file_text(agent_id, agent, roster, existing)
    if existing != text:
        write_atomic(text, path)
    return path


